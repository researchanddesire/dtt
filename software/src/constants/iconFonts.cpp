// Get font pointer by name
// streamline -> funIconsFont (streamline.bdf)
// siji -> wifiFont (siji.bdf)  
// unifont -> timeoutFont (unifont.bdf)
const uint8_t* getFontByName(const String& fontName) {
    String lowerFontName = fontName;
    lowerFontName.toLowerCase();
    
    if (lowerFontName == "streamline") {
        return funIconsFont;
    } else if (lowerFontName == "siji") {
        return wifiFont;
    } else if (lowerFontName == "unifont") {
        return timeoutFont;
    }
    
    // Default to streamline if unknown font name
    return funIconsFont;
}
